set_xmakever("3.0.0")
set_project("PhosphorHUD")
set_version("0.9.24")
set_languages("c++23")
set_encodings("utf-8")
set_warnings("allextra")
add_rules("mode.release", "mode.debug")

local commonlib = os.getenv("COMMONLIBF4_PATH")
if not commonlib or commonlib == "" then
    raise("Set COMMONLIBF4_PATH to the CommonLibF4-NG checkout")
end
includes(commonlib)
add_requires("spdlog", {configs = {header_only = false, wchar = true, std_format = true}})
add_requires("nlohmann_json")
add_requires("valijson 1.1.3")

target("phosphor-core")
    set_kind("static")
    set_arch("x64")
    add_files("src/Core.cpp", "src/ModData.cpp")
    add_includedirs("src", {public = true})
    add_packages("nlohmann_json", {public = true})
    add_packages("valijson")
    add_cxxflags("/EHsc", "/utf-8")

target("phosphor-tests")
    set_kind("binary")
    set_arch("x64")
    add_deps("phosphor-core")
    add_files("tests/core_tests.cpp")
    add_cxxflags("/EHsc", "/utf-8")
    set_targetdir("build/tests")

target("PhosphorHUD")
    set_kind("shared")
    set_arch("x64")
    set_filename("PhosphorHUD.dll")
    add_deps("commonlibf4-ng", "phosphor-core")
    add_packages("spdlog", "nlohmann_json")
    add_files("src/Plugin.cpp", "src/PluginSettings.cpp", "src/PluginEvents.cpp", "src/PluginView.cpp", "src/PluginTest.cpp", "src/Live.cpp", "src/Pipboy.cpp", "src/Mods.cpp", "src/Mines.cpp", "src/EngineProbe.cpp", "src/EngineQuests.cpp", "src/QuickLootFirst.cpp")
    add_includedirs("third_party")
    add_defines("COMMONLIB_RUNTIMECOUNT=3", "F4SE_SUPPORT_820")
    add_defines("WINVER=0x0601", "_WIN32_WINNT=0x0601", "WIN32_LEAN_AND_MEAN", "NOMINMAX")
    add_cxxflags("/EHsc", "/permissive-", "/wd4200", "/wd4201", "/wd4324", "/bigobj", "/utf-8")
    add_syslinks("Version", "Ole32", "OleAut32", "User32", "Winmm", "Ws2_32")
    set_symbols("debug")
    add_ldflags("/OPT:REF", "/OPT:ICF", {force = true})
    set_targetdir("build/release")
